#!/usr/bin/env python3
"""Writes SOURCES/ACTIONHINT_LABEL.H: the words the action hint can show beside
its button, as 8-bit coverage masks rendered with DejaVu Sans Bold (Bitstream
Vera licence). Run from the repository root:

    python3 scripts/dev/gen_action_hint_label.py [path/to/DejaVuSans-Bold.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZE = 28
LABELS = [("kLabelClimbEs", "Trepar"), ("kLabelClimbEn", "Climb"), ("kLabelSavingEs", "Guardando"), ("kLabelSavingEn", "Saving")]

font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
height = ascent + descent
out = []
out.append("/* Generated by scripts/dev/gen_action_hint_label.py: the words the action")
out.append(" * hint shows beside its button, as 8-bit coverage, DejaVu Sans Bold %dpx. */" % SIZE)
out.append("#ifndef ACTIONHINT_LABEL_H")
out.append("#define ACTIONHINT_LABEL_H")
out.append("")
out.append("#define ACTION_HINT_LABEL_H %d" % height)
for name, text in LABELS:
    w = int(font.getlength(text)) + 2
    img = Image.new("L", (w, height), 0)
    ImageDraw.Draw(img).text((1, 0), text, fill=255, font=font)
    px = list(img.tobytes())
    out.append("")
    out.append("/* \"%s\" */" % text)
    out.append("#define %s_W %d" % (name, w))
    out.append("static const U8 %s[%s_W * ACTION_HINT_LABEL_H] = {" % (name, name))
    for y in range(height):
        out.append("    " + ", ".join(str(v) for v in px[y * w:(y + 1) * w]) + ",")
    out.append("};")
out.append("")
out.append("#endif")
open("SOURCES/ACTIONHINT_LABEL.H", "w").write("\n".join(out) + "\n")
